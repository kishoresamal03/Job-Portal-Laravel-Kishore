<?php

namespace App\Http\Controllers\Auth;

use App\Http\Controllers\Controller;
use App\Models\User;
use App\Services\OtpService;
use App\Services\OtpDeliveryService;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\RateLimiter;

class OtpLoginController extends Controller
{
    /**
     * Send OTP to email or mobile.
     */
    public function send(
        Request $request,
        OtpService $otpService,
        OtpDeliveryService $deliveryService
    ) {
        $validated = $request->validate([
            'identifier' => ['required', 'string', 'max:255'],
        ]);

        $identifier = trim($validated['identifier']);

        $isEmail = filter_var($identifier, FILTER_VALIDATE_EMAIL);

        $user = $isEmail
            ? User::where('email', strtolower($identifier))->first()
            : User::where('mobile', $identifier)->first();

        if (!$user) {
            return back()->withErrors([
                'identifier' => 'No candidate account was found.',
            ])->withInput();
        }

        if (!$user->hasVerifiedEmail()) {
            return redirect()->route('verification.notice');
        }

        if (!$user->mobile_verified_at) {
            return redirect()->route('mobile.verification.notice');
        }

        // Rate limiting
        $key = 'otp-login-send:' . $user->id . ':' . $request->ip();

        if (RateLimiter::tooManyAttempts($key, 3)) {
            return back()->withErrors([
                'identifier' => 'Too many OTP requests. Please try again later.',
            ])->withInput();
        }

        RateLimiter::hit($key, 300);

        if ($isEmail) {
            // Email OTP generated by Laravel
            $otp = $otpService->generate($user, 'login');

            $deliveryService->sendEmailOtp($user, $otp);

            $method = 'email';
        } else {
            // Mobile OTP generated by SMSGatewayCenter
            $deliveryService->sendMobileOtp($user, '');

            $method = 'mobile';
        }

        session([
            'otp_login_user_id' => $user->id,
            'otp_login_method' => $method,
        ]);

        return redirect()->route('login.otp.form')
            ->with('status', 'Your login OTP has been sent.');
    }

    /**
     * Show OTP verification page.
     */
    public function show()
    {
        if (
            !session()->has('otp_login_user_id') ||
            !session()->has('otp_login_method')
        ) {
            return redirect()->route('login');
        }

        return view('auth.login-otp');
    }

    /**
     * Verify email or mobile OTP.
     */
    public function verify(
        Request $request,
        OtpService $otpService,
        OtpDeliveryService $deliveryService
    ) {
        $request->validate([
            'otp' => ['required', 'digits:6'],
        ]);

        $userId = session('otp_login_user_id');
        $method = session('otp_login_method');

        if (
            !$userId ||
            !in_array($method, ['email', 'mobile'], true)
        ) {
            return redirect()->route('login');
        }

        $user = User::find($userId);

        if (!$user) {
            session()->forget([
                'otp_login_user_id',
                'otp_login_method',
            ]);

            return redirect()->route('login');
        }

        if (!$user->hasVerifiedEmail() || !$user->mobile_verified_at) {
            session()->forget([
                'otp_login_user_id',
                'otp_login_method',
            ]);

            return redirect()->route('login');
        }

        if ($method === 'email') {
            $verified = $otpService->verify(
                $user,
                'login',
                $request->otp
            );
        } else {
            $verified = $deliveryService->verifyMobileOtp(
                $user,
                $request->otp
            );
        }

        if (!$verified) {
            return back()->withErrors([
                'otp' => 'Invalid or expired OTP.',
            ]);
        }

        session()->forget([
            'otp_login_user_id',
            'otp_login_method',
        ]);

        Auth::login($user);

        $request->session()->regenerate();

        return redirect()->intended(route('dashboard'));
    }
}
